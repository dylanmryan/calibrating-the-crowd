def bh(items, q):
    """items: (name, p, note). Returns the BH ranking and how many survive."""
    m = len(items)
    ranked = sorted(items, key=lambda t: t[1])
    keep = 0
    for i, (_, p, _) in enumerate(ranked, start=1):
        if p <= i / m * q:
            keep = i
    return ranked, keep


def build():
    """Derive every discovery's p-value from the frozen logs, with drift."""
    rows = []
    for spec in SPECS:
        pv, ev = extract(spec)
        rows.append({**spec, "p": pv, "evidence": ev})
    return rows


def drift_report(rows):
    print("=== inventory drift: derived-from-logs vs what the inventory carried ===",
          flush=True)
    print("  (a hand-maintained p-value goes stale; this is why the list now reads", flush=True)
    print("   its own logs. 'was' is the pre-2026-09-03 asserted value.)\n", flush=True)
    print(f"  {'claim':<58}{'was':>10}{'now':>10}  {'evidence':<26} moved", flush=True)
    for r in sorted(rows, key=lambda r: r["p"]):
        ratio = r["p"] / r["was"] if r["was"] else float("inf")
        if r["p"] < 1e-4 and r["was"] < 1e-4:
            moved = "-"                       # both astronomically small
        elif 0.5 <= ratio <= 2.0:
            moved = "~same"
        else:
            moved = "WEAKER" if ratio > 1 else "stronger"
        now = f"<{P_FLOOR:.0g}" if r["p"] <= P_FLOOR else f"{r['p']:.2g}"
        print(f"  {r['name'][:57]:<58}{r['was']:>10.2g}{now:>10}  "
              f"{r['evidence']:<30} {moved}", flush=True)
    print(flush=True)


def main():
    rows = build()
    drift_report(rows)

    items = [(r["name"], r["p"], f"{r['log']}.log" +
              (f" [{r['note']}]" if r.get("note") else "")) for r in rows]
    for q in (0.05, 0.10):
        ranked, keep = bh(items, q)
        print(f"=== Benjamini-Hochberg, q={q} ({len(items)} positive claims, "
              f"p-values derived from the frozen logs at run time, clustered p "
              f"where available) ===", flush=True)
        for i, (name, pv, src) in enumerate(ranked, start=1):
            mark = "KEEP" if i <= keep else "drop"
            shown = f"<{P_FLOOR:.0g}" if pv <= P_FLOOR else f"{pv:.2g}"
            print(f"  [{mark}] p={shown:<8} {name}  ({src})", flush=True)
        print(flush=True)

    print("=== held OUT of the BH family: p-value has no generating line ===", flush=True)
    for name, was, why in UNSOURCED:
        print(f"  - {name} (inventory carried p={was:.2g})", flush=True)
        print(f"      {why}", flush=True)
    print(flush=True)

    print("=== nulls / equivalence claims (not FDR-controlled discoveries) ===", flush=True)
    for name, note in NULLS:
        print(f"  - {name}: {note}", flush=True)
    print("\n(retired claims documented in the module docstring)", flush=True)


if __name__ == "__main__":
    main()

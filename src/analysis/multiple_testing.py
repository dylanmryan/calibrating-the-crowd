def logtext(name):
    return (LOGS / f"{name}.log").read_text()


# Below this, the normal tail underflows to exactly 0.0 in float64. Report the
# floor rather than "p=0", which claims more precision than the arithmetic has.
P_FLOOR = 1e-16


def two_sided(z):
    return max(float(2 * (1 - stats.norm.cdf(abs(z)))), P_FLOOR)


def extract(spec):
    """Pull this claim's statistic out of its log and return (p, evidence)."""
    m = re.search(spec["pat"], logtext(spec["log"]), re.M | re.S)
    if not m:
        raise AssertionError(
            f"multiple_testing: {spec['log']}.log no longer matches the pattern for "
            f"'{spec['name']}'. A claim that cannot find its evidence must not be "
            f"carried — fix the pattern or retire the claim.")
    k = spec["kind"]
    if k == "p":
        return float(m.group(1)), f"p={m.group(1)}"
    if k == "z":
        z = float(m.group(1))                      # magnitude; sign is in the log line
        return two_sided(z), f"|z|={z:.2f}"
    if k == "two_prop":
        n1, p1 = float(m.group(1).replace(",", "")), float(m.group(2))
        n2, p2 = float(m.group(3).replace(",", "")), float(m.group(4))
        pool = (p1 * n1 + p2 * n2) / (n1 + n2)
        se = np.sqrt(pool * (1 - pool) * (1 / n1 + 1 / n2))
        z = (p2 - p1) / se
        return two_sided(z), f"{p2:.3f} vs {p1:.3f}, |z|={abs(z):.2f}"
    if k == "ratio_t":
        ret, se, g = float(m.group(1)), float(m.group(2)), int(m.group(3))
        t = (ret - 1.0) / se
        return float(2 * stats.t.cdf(-abs(t), g - 1)), f"${ret:.2f} vs $1, t={t:+.2f} on {g-1} df"
    raise ValueError(k)


